/**
 * Resuelve la fecha YYYY-MM-DD exacta para un año dado.
 * Si el ítem tiene `recurringAnnual: true`, reemplaza el año por `targetYear` (usando MM-DD).
 * Si no es recurrente anual (fechas móviles como Carnaval / Pascua / Día del Padre), solo aplica si el año coincide.
 */
export function resolveHolidayDateForYear(item: CalendarHolidayItem, targetYear: number): string | null {
  if (!item || !item.date) return null;
  const raw = String(item.date).trim();
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(raw);
  if (!m) return null;
  const itemYear = Number(m[1]);
  const mm = m[2];
  const dd = m[3];
  if (item.recurringAnnual) {
    return `${targetYear}-${mm}-${dd}`;
  }
  return itemYear === targetYear ? `${itemYear}-${mm}-${dd}` : null;
}

